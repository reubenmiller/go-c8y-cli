// v2-based tenant statistics list: lists tenant usage statistics for the given
// date window via Tenants.UsageStatistics.ListAll. No pipeline input, so the
// command runs once.
package list

import (
	"github.com/MakeNowJust/heredoc/v2"
	"github.com/reubenmiller/go-c8y-cli/v2/pkg/c8ystream"
	"github.com/reubenmiller/go-c8y-cli/v2/pkg/cmd/subcommand"
	"github.com/reubenmiller/go-c8y-cli/v2/pkg/cmdutil"
	"github.com/reubenmiller/go-c8y-cli/v2/pkg/flags"
	"github.com/reubenmiller/go-c8y/v2/pkg/c8y/api/pagination"
	"github.com/reubenmiller/go-c8y/v2/pkg/c8y/api/tenants/usagestatistics"
	"github.com/spf13/cobra"
)

// ListCmd command
type ListCmd struct {
	*subcommand.SubCommand

	factory *cmdutil.Factory
}

// NewListCmd creates a command to Get tenant usage statistics
func NewListCmd(f *cmdutil.Factory) *ListCmd {
	ccmd := &ListCmd{
		factory: f,
	}
	cmd := &cobra.Command{
		Use:   "list",
		Short: "Get tenant usage statistics",
		Long:  `Get a collection of tenant usage statistics`,
		Example: heredoc.Doc(`
$ c8y tenantstatistics list
Get tenant statistics collection

$ c8y tenantstatistics list --dateFrom "-30d" --pageSize 30
Get tenant statistics collection for the last 30 days

$ c8y tenantstatistics list --dateFrom "-3d" --dateTo "-2d"
Get tenant statistics collection for the day before yesterday
        `),
		PreRunE: func(cmd *cobra.Command, args []string) error {
			return nil
		},
		RunE: ccmd.RunE,
	}

	cmd.SilenceUsage = true

	cmd.Flags().String("dateFrom", "", "Start date or date and time of the statistics.")
	cmd.Flags().String("dateTo", "", "End date or date and time of the statistics.")

	flags.WithOptions(
		cmd,
		flags.WithCollectionProperty("usageStatistics"),
		flags.WithPowershellName("Get-TenantStatisticsCollection"),
		flags.WithOutputType("application/vnd.com.nsn.cumulocity.tenantUsageStatisticsCollection+json", "application/vnd.com.nsn.cumulocity.tenantUsageStatisticsSummary+json"),
	)

	ccmd.SubCommand = subcommand.NewSubCommand(cmd)

	return ccmd
}

// RunE executes the command
func (n *ListCmd) RunE(cmd *cobra.Command, args []string) error {
	r, err := c8ystream.NewRunner(cmd, n.factory)
	if err != nil {
		return err
	}

	client, err := r.Client()
	if err != nil {
		return err
	}

	common, err := r.Config.GetOutputCommonOptions(cmd)
	if err != nil {
		return err
	}

	rawOutput := r.Config.RawOutput()
	paginationStrategy := pagination.StrategyKind(r.Config.PaginationStrategy())

	return r.Run(func(in *c8ystream.Resolver) (c8ystream.Call, error) {
		opt := usagestatistics.ListOptions{
			DateFrom: in.TimeValue("dateFrom"),
			DateTo:   in.TimeValue("dateTo"),
		}
		opt.PaginationOptions = pagination.PaginationOptions{
			PageSize:          common.PageSize,
			WithTotalPages:    common.WithTotalPages,
			WithTotalElements: common.WithTotalElements,
			CurrentPage:       int(common.CurrentPage),
			MaxItems:          r.Config.MaxItems(),
			Strategy:          paginationStrategy,
		}
		return c8ystream.ListCall(rawOutput, opt, client.Tenants.UsageStatistics.ListAll), nil
	})
}
